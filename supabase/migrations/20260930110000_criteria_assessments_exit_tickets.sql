-- 6. QR self-assessment sessions
-- =============================================================================
-- A pupil opens /s/:token and writes through api/self-assessment, which uses
-- the service role after checking the token and its validity. There is no
-- public RLS policy: without the endpoint nobody but the teacher gets in.

create table if not exists public.self_assessment_sessions (
  id uuid primary key default gen_random_uuid(),
  teacher_id uuid not null references auth.users(id) on delete cascade,
  lesson_id uuid not null references public.lessons(id) on delete cascade,
  -- 64 hex characters from two random UUIDs, no extension needed.
  token text not null unique
    default replace(gen_random_uuid()::text || gen_random_uuid()::text, '-', ''),
  expires_at timestamptz not null default (date_trunc('day', now()) + interval '1 day'),
  closed_at timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists self_assessment_sessions_lesson_idx on public.self_assessment_sessions (lesson_id);

alter table public.self_assessment_sessions enable row level security;

drop policy if exists "Teachers manage own self-assessment sessions" on public.self_assessment_sessions;
create policy "Teachers manage own self-assessment sessions" on public.self_assessment_sessions
  for all
  using (teacher_id = auth.uid())
  with check (
    teacher_id = auth.uid()
    and exists (select 1 from public.lessons l where l.id = lesson_id and l.teacher_id = auth.uid())
  );

