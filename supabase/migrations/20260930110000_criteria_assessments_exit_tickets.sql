-- =============================================================================
-- 4. Criterion assessments: the core of the new version
-- =============================================================================
-- No unique constraint: every entry is a new row and the history is the table.
-- The current level is the latest row per pupil × criterion × source (see the
-- view below).

create table if not exists public.criterion_assessments (
  id uuid primary key default gen_random_uuid(),
  teacher_id uuid not null references auth.users(id) on delete cascade,
  student_id uuid not null references public.students(id) on delete cascade,
  criterion_id uuid not null references public.evaluation_criteria(id) on delete cascade,
  level text not null check (level in ('J', 'C', 'T', 'U')),
  source text not null check (source in ('teacher', 'self_qr', 'self_paper')),
  lesson_id uuid references public.lessons(id) on delete set null,
  proof_id uuid references public.proofs_of_learning(id) on delete set null,
  exit_ticket_id uuid references public.exit_tickets(id) on delete cascade,
  assessed_at timestamptz not null default now(),
  confirmed_by_teacher boolean not null default false,
  note text not null default '',
  created_at timestamptz not null default now()
);

create index if not exists criterion_assessments_current_idx
  on public.criterion_assessments (student_id, criterion_id, source, assessed_at desc, created_at desc);
create index if not exists criterion_assessments_criterion_idx on public.criterion_assessments (criterion_id);
create index if not exists criterion_assessments_teacher_idx on public.criterion_assessments (teacher_id);
create index if not exists criterion_assessments_lesson_idx on public.criterion_assessments (lesson_id);
create index if not exists criterion_assessments_exit_ticket_idx on public.criterion_assessments (exit_ticket_id);

alter table public.criterion_assessments enable row level security;

-- A teacher reads and writes only their own rows, and may not attach a level
-- to someone else's pupil or criterion.
drop policy if exists "Teachers manage own criterion assessments" on public.criterion_assessments;
create policy "Teachers manage own criterion assessments" on public.criterion_assessments
  for all
  using (teacher_id = auth.uid())
  with check (
    teacher_id = auth.uid()
    and exists (select 1 from public.students s where s.id = student_id and s.teacher_id = auth.uid())
    and exists (
      select 1
        from public.evaluation_criteria c
        join public.educational_goals g on g.id = c.goal_id
       where c.id = criterion_id and g.teacher_id = auth.uid()
    )
  );

-- Current level per pupil × criterion × source. security_invoker makes the
-- view obey the RLS of the table underneath.
create or replace view public.current_criterion_levels
with (security_invoker = true) as
select distinct on (student_id, criterion_id, source)
       id,
       teacher_id,
       student_id,
       criterion_id,
       source,
       level,
       assessed_at,
       lesson_id,
       proof_id,
       exit_ticket_id,
       confirmed_by_teacher
  from public.criterion_assessments
 order by student_id, criterion_id, source, assessed_at desc, created_at desc;

-- =============================================================================
-- 5. Old goal levels → criterion assessments
-- =============================================================================
-- A goal level applies to every criterion of the goal, with source "teacher".
-- Rows the mapping cannot place are left out; see the preview query in the PR.

insert into public.criterion_assessments
  (teacher_id, student_id, criterion_id, level, source, assessed_at, note)
select sgl.teacher_id,
       sgl.student_id,
       c.id,
       public.legacy_level_to_jctu(sgl.level, public.goal_level_names(sgl.goal_id)),
       'teacher',
       coalesce(sgl.updated_at, sgl.created_at, now()),
       'Převedeno z úrovně cíle: ' || sgl.level
  from public.student_goal_levels sgl
  join public.evaluation_criteria c on c.goal_id = sgl.goal_id
 where public.legacy_level_to_jctu(sgl.level, public.goal_level_names(sgl.goal_id)) is not null
   and not exists (
     select 1 from public.criterion_assessments ca
      where ca.student_id = sgl.student_id
        and ca.criterion_id = c.id
        and ca.note like 'Převedeno z úrovně cíle:%'
   );

-- The capture tool, course overview and dashboard still write goal levels
-- until phase 7 replaces them. Until then every change is mirrored here, so
-- no level is recorded in one place only. Phase 7 drops the old table and
-- this trigger together.
-- Runs as the caller, so the RLS check on criterion_assessments applies: a goal
-- level on someone else's goal cannot turn into a criterion row.
create or replace function public.mirror_goal_level_to_criteria()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  code text;
begin
  if tg_op = 'DELETE' then
    delete from public.criterion_assessments ca
     using public.evaluation_criteria c
     where c.goal_id = old.goal_id
       and ca.criterion_id = c.id
       and ca.student_id = old.student_id
       and ca.source = 'teacher'
       and ca.note like 'Převedeno z úrovně cíle:%';
    return old;
  end if;

  code := public.legacy_level_to_jctu(new.level, public.goal_level_names(new.goal_id));
  if code is not null then
    insert into public.criterion_assessments
      (teacher_id, student_id, criterion_id, level, source, assessed_at, note)
    select new.teacher_id, new.student_id, c.id, code, 'teacher', now(),
           'Převedeno z úrovně cíle: ' || new.level
      from public.evaluation_criteria c
     where c.goal_id = new.goal_id;
  end if;
  return new;
end;
$$;

drop trigger if exists mirror_goal_level_to_criteria on public.student_goal_levels;
create trigger mirror_goal_level_to_criteria
  after insert or delete or update of level on public.student_goal_levels
  for each row execute function public.mirror_goal_level_to_criteria();

