-- Map an old level name onto the nearest JČTÚ code.
--
-- Old levels were free text taken from the goal's own level list: the default
-- "Začínám / Rozvíjím se / Ovládám", or names the AI proposed such as
-- "Výborně ovládl/a" or "S pomocí zvládl/a". Words decide first; the order is
-- deliberate ("nezvládl" before "zvládl", "s pomocí" and "dobře" before the
-- top level). Only a name no word recognises falls back to its position in the
-- goal's list, read from lowest to highest.
create or replace function public.legacy_level_to_jctu(p_level text, p_levels text[])
returns text
language plpgsql
immutable
as $$
declare
  idx int;
  n int;
  codes text[] := array['J', 'C', 'T', 'U'];
begin
  if p_level is null or btrim(p_level) = '' then
    return null;
  end if;
  if p_level ~* '(začín|nezvl|neosvoj|ještě|zatím|nezvlád)' then return 'J'; end if;
  if p_level ~* '(rozvíj|částeč|s pomocí|s dopomoc|základn)' then return 'C'; end if;
  if p_level ~* '(téměř|skoro|dobře|optimáln)' then return 'T'; end if;
  if p_level ~* '(ovlád|výborn|úplně|zvládl|zvládá|nadstandard|osvojen)' then return 'U'; end if;

  idx := array_position(p_levels, p_level);
  n := coalesce(array_length(p_levels, 1), 0);
  if idx is null or n = 0 then
    return null;
  end if;
  if n = 1 then
    return 'U';
  end if;
  return codes[1 + round((idx - 1) * 3.0 / (n - 1))::int];
end;
$$;

-- The goal's level names in order, from its first criterion.
create or replace function public.goal_level_names(p_goal_id uuid)
returns text[]
language sql
stable
set search_path = public
as $$
  select coalesce(array_agg(ld ->> 'level' order by ord), '{}')
    from (
      select level_descriptors
        from public.evaluation_criteria
       where goal_id = p_goal_id
       order by sort_order, created_at
       limit 1
    ) c,
    jsonb_array_elements(c.level_descriptors) with ordinality as t(ld, ord);
$$;

-- Backfill the new columns from the old ones.
update public.evaluation_criteria
   set teacher_text = description
 where teacher_text is null;

update public.evaluation_criteria c
   set position = r.pos
  from (
    select id, row_number() over (partition by goal_id order by sort_order, created_at) as pos
      from public.evaluation_criteria
  ) r
 where c.id = r.id and c.position is null;

-- Old level descriptions become the scale where every code gets a sentence.
-- A partial mapping (the old three-step scale has no "T") stays null: the scale
-- is regenerated by prompt 03 instead of being half made up.
update public.evaluation_criteria c
   set scale = m.scale
  from (
    select c2.id, jsonb_object_agg(x.code, x.description) as scale
      from public.evaluation_criteria c2
      cross join lateral (
        select distinct on (code) code, description
          from (
            select public.legacy_level_to_jctu(ld ->> 'level', public.goal_level_names(c2.goal_id)) as code,
                   ld ->> 'description' as description,
                   ord
              from jsonb_array_elements(c2.level_descriptors) with ordinality as t(ld, ord)
          ) mapped
         where code is not null and coalesce(btrim(description), '') <> ''
         order by code, ord
      ) x
     group by c2.id
    having count(*) = 4
  ) m
 where c.id = m.id and c.scale is null;

-- Until the old goal editor is replaced, it writes only `description` and
-- `sort_order`. Keep the new columns in step so nothing reads a stale value.
create or replace function public.sync_criterion_legacy_columns()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if new.teacher_text is null
     or (tg_op = 'UPDATE' and old.description is distinct from new.description
         and old.teacher_text is not distinct from old.description) then
    new.teacher_text := new.description;
  end if;
  if new.position is null then
    new.position := new.sort_order + 1;
  end if;
  return new;
end;
$$;

drop trigger if exists sync_criterion_legacy_columns on public.evaluation_criteria;
create trigger sync_criterion_legacy_columns
  before insert or update on public.evaluation_criteria
  for each row execute function public.sync_criterion_legacy_columns();

