-- Phase 2 of the new version: the data model around criteria.
--
-- A lesson has one goal, the goal has (up to three) criteria, and every
-- criterion carries a teacher's and a pupil's wording plus a four-step scale
-- J < Č < T < Ú for the pupil. What a pupil has reached is recorded per
-- criterion in `criterion_assessments`, one row per entry, so the history
-- builds itself. Exit tickets and QR self-assessment write into the same table.
--
-- Codes are stored as ASCII: J, C (Č), T, U (Ú). Labels live in
-- src/constants/jctu.ts.

